package fr.lordfinn.craftmaster.studio;

import fr.lordfinn.craftmaster.CraftMaster;
import fr.lordfinn.craftmaster.block.Shapes4;
import fr.lordfinn.craftmaster.registry.ModContent;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.TransparentBlock;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.phys.shapes.VoxelShape;

import java.util.Set;

/**
 * LordFinn's own furniture, brought over from the ItemsAdder pack of his server (scripts/ia_sandbox, generated by
 * scripts/gen_furniture.py): the throne's look, the contestants' chair, the studio lights and softboxes, the frame,
 * the tripod and its rod, the black and white tiles and the globe panel.
 *
 * <p>On the server those pieces were item models shown by an invisible item frame (or an item display for the
 * softboxes), several blocks tall. Here the block keeps the behaviour (seat, light, collision) and its block entity
 * draws the same item model the same way ({@link Look}).
 */
public final class Furniture {

    private Furniture() {}

    /** How the server showed the model: an invisible item frame (FIXED transform) or an item display (HEAD). */
    public enum Mount { FRAME, DISPLAY }

    /** The item model ({@code assets/craftmaster/items/<model>.json}) a block state is drawn with. */
    public record Look(Identifier model, Mount mount) {}

    public static FurnitureSeatBlock CANDIDATE_CHAIR;
    public static FurnitureBlock STUDIO_LIGHT, SOFTBOX, DECOR_FRAME;
    public static DecorBlock TRIPOD;
    /** The tripod's rod, which links into rigs (towers, beams, junctions) on all 6 sides. */
    public static RigRodBlock TRIPOD_ROD;
    public static Block CHECKER_TILE;
    public static TransparentBlock GLOBE_PANEL;
    public static BlockEntityType<FurnitureBlockEntity> BE;

    /** Called by {@link Studio#register()} once the throne exists. */
    static void register() {
        // Seat cushion top at 12 px (the model's cushion), backrest on the south side when facing north
        CANDIDATE_CHAIR = ModContent.block("candidate_chair", p -> new FurnitureSeatBlock(p, 12, Shapes4.of(
                        new double[]{1.5, 0, 1.5, 14.5, 12, 14.5}, new double[]{1.5, 12, 13.5, 14.5, 16, 15})),
                props(MapColor.COLOR_ORANGE, 2f).sound(SoundType.WOOD).noOcclusion());
        // On the floor, hung under a ceiling or a rig rod, or on a wall / a rod's side (rig: see RigRodBlock)
        STUDIO_LIGHT = ModContent.block("studio_light", p -> new FurnitureBlock(p, 5, true,
                        Block.box(4, 0, 4, 12, 8, 12), Block.box(3, 3, 3, 13, 13, 13), Block.box(4, 8, 4, 12, 16, 12))
                        .turnsInPlaceOnWalls(),
                light(MapColor.COLOR_BLACK));
        VoxelShape soft = Block.box(1, 0, 1, 15, 16, 15);
        SOFTBOX = ModContent.block("softbox", p -> new FurnitureBlock(p, 4, true, soft, soft, soft), light(MapColor.COLOR_BLACK));
        DECOR_FRAME = ModContent.block("decor_frame", p -> new FurnitureBlock(p, 1, true,
                        Block.box(0, 0, 0, 16, 2, 16), Block.box(0, 0, 0, 16, 16, 16), Block.box(0, 14, 0, 16, 16, 16)),
                props(MapColor.WOOD, 1f).sound(SoundType.WOOD).noOcclusion().noCollision());
        TRIPOD = ModContent.block("tripod", p -> new DecorBlock(p, Shapes4.of(new double[]{1, 0, 1, 15, 16, 15})),
                props(MapColor.COLOR_BLACK, 1.5f).sound(SoundType.METAL).noOcclusion());
        TRIPOD_ROD = ModContent.block("tripod_rod", RigRodBlock::new,
                props(MapColor.COLOR_BLACK, 1.5f).sound(SoundType.METAL).noOcclusion());
        CHECKER_TILE = ModContent.block("checker_tile", Block::new,
                props(MapColor.QUARTZ, 1.5f).sound(SoundType.STONE).requiresCorrectToolForDrops());
        // Glass: it hides the faces of the panels next to it, not the rest
        GLOBE_PANEL = ModContent.block("globe_panel", p -> new TransparentBlock(p) {},
                props(MapColor.SNOW, 0.3f).sound(SoundType.GLASS).noOcclusion());

        BE = Registry.register(BuiltInRegistries.BLOCK_ENTITY_TYPE, CraftMaster.id("furniture"),
                new BlockEntityType<>(FurnitureBlockEntity::new, Set.of(Studio.THRONE, CANDIDATE_CHAIR, STUDIO_LIGHT, SOFTBOX, DECOR_FRAME)));
    }

    /** The model a furniture block is drawn with, or null for a block that has none. */
    public static Look look(BlockState state) {
        Block b = state.getBlock();
        if (b == Studio.THRONE) return new Look(CraftMaster.id("furniture/throne"), Mount.FRAME);
        if (b == CANDIDATE_CHAIR) return new Look(CraftMaster.id("furniture/candidate_chair"), Mount.FRAME);
        if (b == DECOR_FRAME) return new Look(CraftMaster.id("furniture/decor_frame"), Mount.FRAME);
        if (b == STUDIO_LIGHT) return new Look(CraftMaster.id("furniture/studio_light_" + state.getValue(FurnitureBlock.TILT)), Mount.FRAME);
        if (b == SOFTBOX) return new Look(CraftMaster.id("furniture/softbox_" + Math.min(4, state.getValue(FurnitureBlock.TILT))), Mount.DISPLAY);
        return null;
    }

    private static BlockBehaviour.Properties props(MapColor color, float strength) {
        return BlockBehaviour.Properties.of().mapColor(color).strength(strength, strength * 2);
    }

    /** The studio lights shine like on the server (light level 15). */
    private static BlockBehaviour.Properties light(MapColor color) {
        return props(color, 1f).sound(SoundType.LANTERN).noOcclusion().lightLevel(s -> 15);
    }
}
